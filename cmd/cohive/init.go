// knownTools 是 cohive init 能配置的编程工具，也是 cohive login 默认申请令牌的工具，顺序即显示顺序。
var knownTools = []string{"claude-code", "codex", "opencode"}

func isKnownTool(t string) bool { return slices.Contains(knownTools, t) }

// 影响他人工作、不可撤销的工具每次都要用户确认；其余直接放行。
var (
	confirmTools = []string{"cohive_submit_issue", "cohive_accept_issue", "cohive_close_issue", "cohive_cancel_issue", "cohive_delete_draft"}
	allowTools   = []string{"cohive_inbox", "cohive_get_issue", "cohive_search", "cohive_who_owns", "cohive_find_member",
		"cohive_draft_issue", "cohive_update_issue", "cohive_request_verification", "cohive_watch_issue"}
)

// lookPath 查找命令；测试里替换掉。
var lookPath = exec.LookPath

// Codex 配置里 init 自己管理的那一段的首尾标记。标记是写进仓库、团队共用的文件内容，不随命令行语言变化；
// 以前的版本写过中文的开头标记，所以识别开头只认前缀 blockBeginPrefix，重新执行时换成现在的写法。
const (
	blockBeginPrefix = "# >>> cohive"
	blockBegin       = blockBeginPrefix + " (generated by cohive init; running it again overwrites this block)"
	blockEnd         = "# <<< cohive"
)

func initProject(ctx context.Context, out io.Writer, args []string) error {
	fs := flag.NewFlagSet("init", flag.ContinueOnError)
	dir := fs.String("dir", ".", i18n.T("cli.flag.init.dir"))
	server := fs.String("server", "", i18n.T("cli.flag.init.server"))
	workspace := fs.String("workspace", "", i18n.T("cli.flag.init.workspace"))
	toolsFlag := fs.String("tools", "", i18n.T("cli.flag.init.tools"))
	command := fs.String("command", "cohive", i18n.T("cli.flag.init.command"))
	noHooks := fs.Bool("no-hooks", false, i18n.T("cli.flag.init.no_hooks"))
	if err := fs.Parse(args); err != nil {
		return err
	}
	creds, err := client.LoadCredentials()
	if err != nil {
		return err
	}
	srv, ws, err := pickTarget(ctx, creds, *server, *workspace)
	if err != nil {
		return err
	}
	dev, hasDev := creds.Device(srv)

	var tools []string
	if *toolsFlag == "" {
		// 默认：这台电脑在这个服务上登录过的工具（新加入的工作空间还没有令牌，按其他工作空间的算）
		for _, t := range knownTools {
			for _, l := range creds.Logins {
				if l.Server == srv && l.Tool == t && (hasDev || l.Workspace == ws) {
					tools = append(tools, t)
					break
				}
			}
		}
		if len(tools) == 0 {
			return i18n.Errorf("cli.init.not_logged_in_tools", i18n.D{"Workspace": ws})
		}
	} else {
		for _, t := range strings.Split(*toolsFlag, ",") {
			t = strings.TrimSpace(t)
			if !isKnownTool(t) {
				return i18n.Errorf("cli.init.tools_unsupported", i18n.D{"Tool": strconv.Quote(t), "Known": strings.Join(knownTools, ", ")})
			}
			tools = append(tools, t)
		}
	}

	proxyArgs := func(tool string) []string {
		return []string{"mcp-proxy", "--server", srv, "--workspace", ws, "--tool", tool}
	}
	// 会话钩子的命令（参数列表）；为空表示不写（并移除以前写的）
	hookArgv := func(tool string) []string {
		if *noHooks {
			return nil
		}
		return append([]string{*command, "hook"}, proxyArgs(tool)[1:]...)
	}
	hookCmd := func(tool string) string {
		if *noHooks {
			return ""
		}
		return shellCommand(hookArgv(tool))
	}
	var written []string
	for _, t := range tools {
		switch t {
		case "claude-code":
			if err := initClaude(*dir, *command, proxyArgs(t), hookCmd(t)); err != nil {
				return err
			}
			written = append(written, i18n.T("cli.init.written_claude"))
		case "codex":
			if err := initCodex(*dir, *command, proxyArgs(t), hookCmd(t)); err != nil {
				return err
			}
			written = append(written, i18n.T("cli.init.written_codex"))
		case "opencode":
			if err := initOpencode(*dir, *command, proxyArgs(t), hookArgv(t)); err != nil {
				return err
			}
			if *noHooks {
				written = append(written, i18n.T("cli.init.written_opencode"))
			} else {
				written = append(written, i18n.T("cli.init.written_opencode_plugin"))
			}
		}
	}

	fmt.Fprint(out, i18n.T("cli.init.wrote_config", i18n.D{"Workspace": ws, "Server": srv}))
	for _, w := range written {
		fmt.Fprintf(out, "  %s\n", w)
	}
	fmt.Fprintln(out, i18n.T("cli.init.no_tokens_note"))
	if !*noHooks {
		fmt.Fprintln(out, i18n.T("cli.init.hooks_note"))
		for _, t := range tools {
			switch t {
			case "claude-code":
				fmt.Fprintln(out, i18n.T("cli.init.hook_claude"))
			case "codex":
				fmt.Fprintln(out, i18n.T("cli.init.hook_codex"))
			case "opencode":
				fmt.Fprintln(out, i18n.T("cli.init.hook_opencode"))
			}
		}
		fmt.Fprint(out, i18n.T("cli.init.hook_check", i18n.D{
			"Command": shellCommand(append([]string{*command, "hook", "--check"}, proxyArgs(tools[0])[1:]...))}))
	}
	// 编程工具按配置里的命令启动转发器：命令不在 PATH 里时它会找不到 cohive
	if _, err := lookPath(*command); err != nil {
		fmt.Fprint(out, i18n.T("cli.init.path_missing", i18n.D{"Command": strconv.Quote(*command)}))
	}
	// 有设备密钥时顺手补签这个工作空间缺的令牌（新加入的工作空间不必重新配对）
	var missing []string
	for _, t := range tools {
		if _, ok := creds.Find(srv, ws, t); !ok {
			missing = append(missing, t)
		}
	}
	if len(missing) > 0 && hasDev {
		wt, err := client.IssueTokens(ctx, srv, dev.Secret, ws, missing)
		if err != nil {
			return err
		}
		for _, t := range knownToolsFirst(wt.Tokens) {
			creds.Upsert(client.Login{Server: srv, Workspace: ws, Member: dev.Account, Tool: t, Token: wt.Tokens[t], DeviceID: dev.DeviceID})
		}
		if err := creds.Save(); err != nil {
			return err
		}
		fmt.Fprint(out, i18n.T("cli.init.tokens_issued", i18n.D{"Workspace": ws, "Tools": listJoin(missing)}))
		missing = nil
	}
	for _, t := range missing {
		fmt.Fprint(out, i18n.T("cli.init.tool_not_logged_in", i18n.D{"Tool": t}))
	}
	fmt.Fprintln(out, i18n.T("cli.init.next_header"))
	fmt.Fprintln(out, i18n.T("cli.init.next_1"))
	fmt.Fprintln(out, i18n.T("cli.init.next_2"))
	return nil
}

// pickTarget 决定配置哪个服务与工作空间：显式指定优先。服务：本机必须只配对过一个；
// 工作空间：有设备密钥时按服务端返回的“我所在的工作空间”，只有一个时可省略；旧版配对按本机登录过的。
func pickTarget(ctx context.Context, creds *client.Credentials, server, workspace string) (string, string, error) {
	servers := map[string]bool{}
	for _, d := range creds.Devices {
		servers[d.Server] = true
	}
	for _, l := range creds.Logins {
		servers[l.Server] = true
	}
	if len(servers) == 0 {
		return "", "", i18n.Errorf("cli.init.not_logged_in")
	}
	srv := client.NormalizeServer(server)
	if srv == "" {
		if len(servers) > 1 {
			var list []string
			for s := range servers {
				list = append(list, "--server "+s)
			}
			sort.Strings(list)
			return "", "", i18n.Errorf("cli.multiple_servers", i18n.D{"List": strings.Join(list, "\n  ")})
		}
		for s := range servers {
			srv = s
		}
	} else if !servers[srv] {
		return "", "", i18n.Errorf("cli.init.server_not_logged_in", i18n.D{"Server": srv})
	}
	var names []string
	dev, hasDev := creds.Device(srv)
	if hasDev {
		wss, err := client.DeviceWorkspaces(ctx, srv, dev.Secret)
		if err != nil {
			return "", "", err
		}
		for _, w := range wss {
			// 没指定工作空间时不在已归档的里挑；明确指定的仍然认
			if w.Archived && workspace == "" {
				continue
			}
			names = append(names, w.Name)
		}
	} else {
		seen := map[string]bool{}
		for _, l := range creds.Logins {
			if l.Server == srv && !seen[l.Workspace] {
				seen[l.Workspace] = true
				names = append(names, l.Workspace)
			}
		}
	}
	if workspace != "" {
		for _, n := range names {
			if n == workspace {
				return srv, workspace, nil
			}
		}
		// 只有设备密钥能向服务端确认“我在哪些工作空间”；没有它时本机只知道登录过的工作空间，
		// 不能断定“不是成员”，先说清楚是这台电脑的配对方式不够用
		if _, legacy := creds.LegacyDevice(srv); legacy {
			return "", "", i18n.Errorf("cli.init.legacy_pairing", i18n.D{"Workspace": workspace, "Server": srv})
		}
		if !hasDev {
			return "", "", i18n.Errorf("cli.init.no_workspace_login", i18n.D{"Workspace": workspace, "Server": srv})
		}
		return "", "", i18n.Errorf("cli.init.not_member", i18n.D{"Workspace": workspace})
	}
	switch len(names) {
	case 0:
		return "", "", i18n.Errorf("cli.init.no_workspaces")
	case 1:
		return srv, names[0], nil
	}
	sort.Strings(names)
	return "", "", i18n.Errorf("cli.init.multiple_workspaces", i18n.D{"List": strings.Join(names, "\n  ")})
}

// checkNoSymlinks 确认 rel 路径上的每一级（从项目目录往下）都不是符号链接。
// 防止别人仓库里预先放好的链接让 init 写到项目之外（例如 ~/.zshrc）。
func checkNoSymlinks(dir, rel string) error {
	p := dir
	for _, part := range strings.Split(filepath.ToSlash(rel), "/") {
		p = filepath.Join(p, part)
		fi, err := os.Lstat(p)
		if errors.Is(err, fs.ErrNotExist) {
			return nil
		}
		if err != nil {
			return err
		}
		if fi.Mode()&os.ModeSymlink != 0 {
			return i18n.Errorf("cli.init.symlink", i18n.D{"Path": p})
		}
	}
	return nil
}

// readJSONObject 读取 JSON 对象；数字保持原样（不转成浮点），文件不存在时返回空对象。
func readJSONObject(path string) (map[string]any, error) {
	b, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return map[string]any{}, nil
	}
	if err != nil {
		return nil, err
	}
	m := map[string]any{}
	if len(strings.TrimSpace(string(b))) == 0 {
		return m, nil
	}
	dec := json.NewDecoder(bytes.NewReader(b))
	dec.UseNumber()
	if err := dec.Decode(&m); err != nil {
		return nil, i18n.Wrap(err, "cli.init.bad_json", i18n.D{"Path": path})
	}
	return m, nil
}

// writeJSON 写回 JSON：不转义 &、<、> 这类字符，保持用户原有内容可读。
func writeJSON(path string, v any) error {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		return err
	}
	return writeFile(path, buf.Bytes())
}

// writeFile 先写同目录下的临时文件再改名，中途失败不会损坏原文件。
func writeFile(path string, b []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+".cohive-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(b); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(0o644); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}

// childObject 取出（或创建）子对象；已有值不是对象时报错，不覆盖用户的内容。
func childObject(m map[string]any, key, path string) (map[string]any, error) {
	switch c := m[key].(type) {
	case map[string]any:
		return c, nil
	case nil:
		if _, exists := m[key]; exists {
			return nil, i18n.Errorf("cli.init.null_not_object", i18n.D{"Path": path})
		}
		c2 := map[string]any{}
		m[key] = c2
		return c2, nil
	default:
		return nil, i18n.Errorf("cli.init.not_object", i18n.D{"Path": path, "Type": fmt.Sprintf("%T", c)})
	}
}

// addStrings 往字符串数组里追加缺少的项，保持原有顺序；已有值不是数组时报错。
func addStrings(m map[string]any, key, path string, items ...string) error {
	var list []any
	if v, exists := m[key]; exists {
		existing, ok := v.([]any)
		if !ok {
			return i18n.Errorf("cli.init.not_array", i18n.D{"Path": path, "Type": fmt.Sprintf("%T", v)})
		}
		list = existing
	}
	have := map[string]bool{}
	for _, v := range list {
		if s, ok := v.(string); ok {
			have[s] = true
		}
	}
	for _, it := range items {
		if !have[it] {
			list = append(list, it)
			have[it] = true
		}
	}
	m[key] = list
	return nil
}

func initClaude(dir, command string, args []string, hookCmd string) error {
	for _, rel := range []string{".mcp.json", ".claude/settings.json", ".claude/skills/cohive/SKILL.md"} {
		if err := checkNoSymlinks(dir, rel); err != nil {
			return err
		}
	}
	mcpPath := filepath.Join(dir, ".mcp.json")
	mcp, err := readJSONObject(mcpPath)
	if err != nil {
		return err
	}
	servers, err := childObject(mcp, "mcpServers", i18n.T("cli.init.at.mcp_servers"))
	if err != nil {
		return err
	}
	argv := make([]any, len(args))
	for i, a := range args {
		argv[i] = a
	}
	servers["cohive"] = map[string]any{"type": "stdio", "command": command, "args": argv}

	settingsPath := filepath.Join(dir, ".claude", "settings.json")
	settings, err := readJSONObject(settingsPath)
	if err != nil {
		return err
	}
	perms, err := childObject(settings, "permissions", i18n.T("cli.init.at.permissions"))
	if err != nil {
		return err
	}
	prefixed := func(names []string) []string {
		out := make([]string, len(names))
		for i, n := range names {
			out[i] = "mcp__cohive__" + n
		}
		return out
	}
	if err := addStrings(perms, "allow", i18n.T("cli.init.at.permissions_allow"), prefixed(allowTools)...); err != nil {
		return err
	}
	if err := addStrings(perms, "ask", i18n.T("cli.init.at.permissions_ask"), prefixed(confirmTools)...); err != nil {
		return err
	}
	if err := addStrings(settings, "enabledMcpjsonServers", i18n.T("cli.init.at.enabled_servers"), "cohive"); err != nil {
		return err
	}
	if err := setClaudeHooks(settings, hookCmd); err != nil {
		return err
	}
	// 全部校验通过后再写，避免只写了一半
	if err := writeJSON(mcpPath, mcp); err != nil {
		return err
	}
	if err := writeJSON(settingsPath, settings); err != nil {
		return err
	}
	return writeSkill(filepath.Join(dir, ".claude", "skills", "cohive", "SKILL.md"))
}

func tomlString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u%04X`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func codexBlock(command string, args []string, hookCmd string) string {
	quoted := make([]string, len(args))
	for i, a := range args {
		quoted[i] = tomlString(a)
	}
	var b strings.Builder
	b.WriteString(blockBegin + "\n")
	b.WriteString("[mcp_servers.cohive]\n")
	fmt.Fprintf(&b, "command = %s\n", tomlString(command))
	fmt.Fprintf(&b, "args = [%s]\n", strings.Join(quoted, ", "))
	tools := append(append([]string{}, confirmTools...), allowTools...)
	sort.Strings(tools)
	confirm := map[string]bool{}
	for _, t := range confirmTools {
		confirm[t] = true
	}
	for _, t := range tools {
		mode := "approve"
		if confirm[t] {
			mode = "prompt" // 影响他人工作，每次都要用户确认
		}
		fmt.Fprintf(&b, "\n[mcp_servers.cohive.tools.%s]\napproval_mode = %q\n", t, mode)
	}
	if hookCmd != "" {
		// 会话钩子：每次生成得一模一样，重复执行 init 不会让 /hooks 里的信任失效
		for _, ev := range hookEvents {
			fmt.Fprintf(&b, "\n[[hooks.%s]]\n[[hooks.%s.hooks]]\ntype = \"command\"\ncommand = %s\ntimeout = %d\n", ev, ev, tomlString(hookCmd), hookTimeout)
		}
	}
	b.WriteString(blockEnd + "\n")
	return b.String()
}

// hasCohiveServer 用 TOML 解析判断配置里是否已有 mcp_servers.cohive（任何写法）。
func hasCohiveServer(path, text string) (bool, error) {
	var cfg map[string]any
	if _, err := toml.Decode(text, &cfg); err != nil {
		return false, i18n.Wrap(err, "cli.init.toml_invalid", i18n.D{"Path": path})
	}
	servers, _ := cfg["mcp_servers"].(map[string]any)
	_, ok := servers["cohive"]
	return ok, nil
}

func initCodex(dir, command string, args []string, hookCmd string) error {
	for _, rel := range []string{".codex/config.toml", ".agents/skills/cohive/SKILL.md"} {
		if err := checkNoSymlinks(dir, rel); err != nil {
			return err
		}
	}
	path := filepath.Join(dir, ".codex", "config.toml")
	b, err := os.ReadFile(path)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	text := string(b)

	// 去掉 init 自己管理的那一段，剩下的就是用户自己的配置
	rest, blockAt := text, -1
	if start := strings.Index(text, blockBeginPrefix); start >= 0 {
		end := strings.Index(text[start:], blockEnd)
		if end < 0 {
			return i18n.Errorf("cli.init.block_no_end", i18n.D{"Path": path, "Marker": strconv.Quote(blockEnd)})
		}
		end = start + end + len(blockEnd)
		if end < len(text) && text[end] == '\n' {
			end++
		}
		rest, blockAt = text[:start]+text[end:], start
	}
	if exists, err := hasCohiveServer(path, rest); err != nil {
		return err
	} else if exists {
		return i18n.Errorf("cli.init.handwritten_cohive", i18n.D{"Path": path})
	}

	block := codexBlock(command, args, hookCmd)
	var next string
	if blockAt >= 0 {
		next = rest[:blockAt] + block + rest[blockAt:]
	} else {
		next = rest
		if next != "" && !strings.HasSuffix(next, "\n") {
			next += "\n"
		}
		if next != "" {
			next += "\n"
		}
		next += block
	}
	if _, err := hasCohiveServer(path, next); err != nil {
		return i18n.Wrap(err, "cli.init.generated_invalid")
	}
	if err := writeFile(path, []byte(next)); err != nil {
		return err
	}
	return writeSkill(filepath.Join(dir, ".agents", "skills", "cohive", "SKILL.md"))
}

// 会话钩子：两家都用会话开始、提交提示词两个事件；外层超时兜底（cohive hook 自己 2 秒内结束）。
var hookEvents = []string{"SessionStart", "UserPromptSubmit"}

const hookTimeout = 5

var shellSafe = regexp.MustCompile(`^[A-Za-z0-9_@%+=:,./-]+$`)

// shellCommand 把参数拼成一条 shell 命令，必要时加单引号（两家都按 shell 执行钩子命令）。
func shellCommand(argv []string) string {
	parts := make([]string, len(argv))
	for i, a := range argv {
		if shellSafe.MatchString(a) {
			parts[i] = a
		} else {
			parts[i] = "'" + strings.ReplaceAll(a, "'", `'\''`) + "'"
		}
	}
	return strings.Join(parts, " ")
}

// isCohiveHook 判断一条钩子命令是不是 cohive init 写的：第一个词是 cohive（或其路径），第二个词是 hook。
func isCohiveHook(cmd string) bool {
	f := shellWords(cmd)
	if len(f) < 2 || f[1] != "hook" {
		return false
	}
	return filepath.Base(f[0]) == "cohive"
}

// shellWords 按 shellCommand 的写法拆回参数：空白分隔，单引号内原样，引号外的反斜杠转义下一个字符。
func shellWords(s string) []string {
	var out []string
	var cur strings.Builder
	inWord, quoted, escaped := false, false, false
	for _, r := range s {
		switch {
		case escaped:
			cur.WriteRune(r)
			escaped = false
		case quoted:
			if r == '\'' {
				quoted = false
			} else {
				cur.WriteRune(r)
			}
		case r == '\'':
			quoted, inWord = true, true
		case r == '\\':
			escaped, inWord = true, true
		case r == ' ' || r == '\t' || r == '\n':
			if inWord {
				out = append(out, cur.String())
				cur.Reset()
				inWord = false
			}
		default:
			cur.WriteRune(r)
			inWord = true
		}
	}
	if inWord {
		out = append(out, cur.String())
	}
	return out
}

// setClaudeHooks 在 .claude/settings.json 的 hooks 里为两个事件各放一组 cohive 钩子：
// 先去掉以前写的那组（只含一条 cohive hook 命令的组），用户自己的钩子与顺序不动；hookCmd 为空时只移除。
func setClaudeHooks(settings map[string]any, hookCmd string) error {
	_, had := settings["hooks"]
	if !had && hookCmd == "" {
		return nil
	}
	hooks, err := childObject(settings, "hooks", i18n.T("cli.init.at.hooks"))
	if err != nil {
		return err
	}
	for _, ev := range hookEvents {
		path := i18n.T("cli.init.at.hooks_event", i18n.D{"Event": ev})
		var groups []any
		if v, exists := hooks[ev]; exists {
			list, ok := v.([]any)
			if !ok {
				return i18n.Errorf("cli.init.not_array", i18n.D{"Path": path, "Type": fmt.Sprintf("%T", v)})
			}
			groups = list
		}
		kept := make([]any, 0, len(groups)+1)
		for _, g := range groups {
			if !isCohiveGroup(g) {
				kept = append(kept, g)
			}
		}
		if hookCmd != "" {
			kept = append(kept, map[string]any{"hooks": []any{
				map[string]any{"type": "command", "command": hookCmd, "timeout": json.Number(fmt.Sprint(hookTimeout))},
			}})
		}
		if len(kept) == 0 {
			delete(hooks, ev)
		} else {
			hooks[ev] = kept
		}
	}
	if len(hooks) == 0 {
		delete(settings, "hooks")
	}
	return nil
}

func isCohiveGroup(g any) bool {
	m, ok := g.(map[string]any)
	if !ok {
		return false
	}
	list, ok := m["hooks"].([]any)
	if !ok || len(list) != 1 {
		return false
	}
	h, ok := list[0].(map[string]any)
	if !ok {
		return false
	}
	cmd, _ := h["command"].(string)
	return isCohiveHook(cmd)
}

// writeSkill 写 /cohive 技能文件。项目里已经有 cohive 的技能文件时沿用它原来的语言（按内容判断），
// 免得团队里语言不同的成员各自重新执行 cohive init 时把共用的文件来回改；没有时用命令行的语言。
func writeSkill(path string) error {
	lang := i18n.Default()
	if old, err := os.ReadFile(path); err == nil && len(bytes.TrimSpace(old)) > 0 {
		lang = skill.Detect(old)
	}
	return writeFile(path, skill.For(lang))
}
