// opencode 的 MCP 工具名是“服务名_工具名”，cohive 服务下的工具就是 cohive_cohive_inbox 这样。
const opencodeToolPrefix = "cohive_"

// opencode 的会话内提醒插件：随仓库提交，opencode 启动时自动加载，每次提交提示词时调用 cohive hook。
//
//go:embed opencode_plugin.ts.tmpl
var opencodePluginTmpl string

// 插件文件的第一行：认出是 cohive init 写的才覆盖或移除，用户自己的同名文件不动。
const opencodePluginMarker = "// Generated by cohive init"

const (
	opencodeConfig  = "opencode.json"
	opencodeJSONC   = "opencode.jsonc"
	opencodePlugin  = ".opencode/plugins/cohive.ts"
	sharedSkillPath = ".agents/skills/cohive/SKILL.md" // Codex 用的那份；opencode 也读这个目录，两家共用
)

// opencodePluginSource 生成插件内容：模板里只替换 cohive hook 的参数列表（JSON 数组，也是合法的 TS）。
func opencodePluginSource(hookArgv []string) []byte {
	argv, _ := marshalNoEscape(hookArgv)
	return []byte(strings.Replace(opencodePluginTmpl, "__COHIVE_HOOK_ARGV__", string(argv), 1))
}

// opencodePaths 是 opencode 配置涉及的四个文件的位置：项目级在项目目录下，用户级在 ~/.config/opencode 与 ~/.agents 下。
type opencodePaths struct {
	config, jsonc, plugin, skill string
}

func projectOpencodePaths(dir string) opencodePaths {
	return opencodePaths{
		config: filepath.Join(dir, opencodeConfig),
		jsonc:  filepath.Join(dir, opencodeJSONC),
		plugin: filepath.Join(dir, opencodePlugin),
		skill:  filepath.Join(dir, sharedSkillPath),
	}
}

// initOpencode 写 opencode.json（MCP 与按工具确认）、提醒插件和 /cohive 技能。
// hookArgv 为空表示不写提醒插件，并移除以前 cohive init 写的那份。
func initOpencode(dir, command string, args, hookArgv []string) error {
	for _, rel := range []string{opencodeConfig, opencodeJSONC, opencodePlugin, sharedSkillPath} {
		if err := checkNoSymlinks(dir, rel); err != nil {
			return err
		}
	}
	return initOpencodeAt(projectOpencodePaths(dir), command, args, hookArgv, nil)
}

func initOpencodeAt(p opencodePaths, command string, args, hookArgv []string, extraAllow []string) error {
	// 带注释的 opencode.jsonc 改写后注释会丢；而且两份同时存在时 opencode 两份都读，容易搞不清哪份生效
	if _, err := os.Stat(p.jsonc); err == nil {
		return i18n.Errorf("cli.init.opencode_jsonc", i18n.D{"Path": p.jsonc})
	}
	cfgPath := p.config
	cfg, err := readOrdered(cfgPath)
	if err != nil {
		return err
	}
	if len(cfg) == 0 {
		cfg.set("$schema", json.RawMessage(`"https://opencode.ai/config.json"`))
	}

	// MCP：本机命令方式启动 cohive mcp-proxy；以前的 cohive 条目（任何写法）整个换掉
	mcp, err := cfg.child("mcp", i18n.T("cli.init.at.opencode_mcp"))
	if err != nil {
		return err
	}
	argv, err := marshalNoEscape(append([]string{command}, args...))
	if err != nil {
		return err
	}
	server, err := ordered{{"type", json.RawMessage(`"local"`)}, {"command", argv}}.compact()
	if err != nil {
		return err
	}
	mcp.set("cohive", server)
	if err := cfg.setChild("mcp", mcp); err != nil {
		return err
	}

	// 按工具确认：整体写成字符串（例如 "ask"）时等价于 {"*": 值}，展开后再加规则。
	// opencode 按顺序匹配、最后命中的规则生效，所以 cohive 的规则先删再追加到末尾，压过用户写在前面的通配
	perm, err := cfg.permission()
	if err != nil {
		return err
	}
	for _, t := range append(append([]string{}, allowTools...), extraAllow...) {
		perm.moveToEnd(opencodeToolPrefix+t, json.RawMessage(`"allow"`))
	}
	for _, t := range confirmTools {
		perm.moveToEnd(opencodeToolPrefix+t, json.RawMessage(`"ask"`)) // 影响他人工作，每次都要用户确认
	}
	if err := cfg.setChild("permission", perm); err != nil {
		return err
	}

	// 插件：认出是自己写的才动；用户自己放的同名文件不覆盖也不删
	pluginPath := p.plugin
	old, err := os.ReadFile(pluginPath)
	exists := err == nil
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	ours := exists && strings.HasPrefix(string(old), opencodePluginMarker)
	if exists && !ours && len(hookArgv) > 0 {
		return i18n.Errorf("cli.init.opencode_plugin_foreign", i18n.D{"Path": pluginPath})
	}

	// 全部校验通过后再写，避免只写了一半
	b, err := cfg.encode()
	if err != nil {
		return err
	}
	if err := writeFile(cfgPath, b); err != nil {
		return err
	}
	switch {
	case len(hookArgv) > 0:
		if err := writeFile(pluginPath, opencodePluginSource(hookArgv)); err != nil {
			return err
		}
	case ours:
		if err := os.Remove(pluginPath); err != nil {
			return err
		}
	}
	return writeSkill(p.skill)
}

// ordered 是保持键顺序的 JSON 对象：值原样保留（嵌套内容的顺序、数字写法都不变）。
// opencode 的权限规则按顺序匹配，重排用户的键可能改变含义，所以不能用 map 读写 opencode.json。
type ordered []orderedField

type orderedField struct {
	Key string
	Val json.RawMessage
}

func parseOrdered(b []byte) (ordered, bool) {
	dec := json.NewDecoder(bytes.NewReader(b))
	if t, err := dec.Token(); err != nil || t != json.Delim('{') {
		return nil, false
	}
	var o ordered
	for dec.More() {
		t, err := dec.Token()
		if err != nil {
			return nil, false
		}
		key, ok := t.(string)
		if !ok {
			return nil, false
		}
		var raw json.RawMessage
		if err := dec.Decode(&raw); err != nil {
			return nil, false
		}
		o.set(key, raw)
	}
	if t, err := dec.Token(); err != nil || t != json.Delim('}') {
		return nil, false
	}
	if _, err := dec.Token(); err == nil {
		return nil, false // 对象后面还有内容
	}
	return o, true
}

// readOrdered 读取 JSON 对象；文件不存在或为空时返回空对象。
func readOrdered(path string) (ordered, error) {
	b, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return ordered{}, nil
	}
	if err != nil {
		return nil, err
	}
	if len(bytes.TrimSpace(b)) == 0 {
		return ordered{}, nil
	}
	if !json.Valid(b) {
		var v any
		return nil, i18n.Wrap(json.Unmarshal(b, &v), "cli.init.bad_json", i18n.D{"Path": path})
	}
	o, ok := parseOrdered(b)
	if !ok {
		return nil, i18n.Errorf("cli.init.not_object", i18n.D{"Path": path, "Type": jsonKind(b)})
	}
	return o, nil
}

func (o ordered) index(key string) int {
	for i, f := range o {
		if f.Key == key {
			return i
		}
	}
	return -1
}

// set 改写已有的键（位置不变），没有时追加。
func (o *ordered) set(key string, v json.RawMessage) {
	if i := o.index(key); i >= 0 {
		(*o)[i].Val = v
		return
	}
	*o = append(*o, orderedField{key, v})
}

// remove 删掉一个键，没有时什么都不做。
func (o *ordered) remove(key string) {
	if i := o.index(key); i >= 0 {
		*o = append((*o)[:i], (*o)[i+1:]...)
	}
}

// moveToEnd 删掉已有的键再追加到末尾。
func (o *ordered) moveToEnd(key string, v json.RawMessage) {
	if i := o.index(key); i >= 0 {
		*o = append((*o)[:i], (*o)[i+1:]...)
	}
	*o = append(*o, orderedField{key, v})
}

// child 取出子对象；没有时为空对象，已有值不是对象时报错，不覆盖用户的内容。
func (o ordered) child(key, path string) (ordered, error) {
	i := o.index(key)
	if i < 0 {
		return ordered{}, nil
	}
	c, ok := parseOrdered(o[i].Val)
	if !ok {
		if bytes.Equal(bytes.TrimSpace(o[i].Val), []byte("null")) {
			return nil, i18n.Errorf("cli.init.null_not_object", i18n.D{"Path": path})
		}
		return nil, i18n.Errorf("cli.init.not_object", i18n.D{"Path": path, "Type": jsonKind(o[i].Val)})
	}
	return c, nil
}

// permission 取出 permission：对象原样；字符串 "allow"、"ask"、"deny" 展开成 {"*": 值}；其他写法报错。
func (o ordered) permission() (ordered, error) {
	path := i18n.T("cli.init.at.opencode_permission")
	if i := o.index("permission"); i >= 0 {
		var s string
		if json.Unmarshal(o[i].Val, &s) == nil {
			if s != "allow" && s != "ask" && s != "deny" {
				return nil, i18n.Errorf("cli.init.not_object", i18n.D{"Path": path, "Type": jsonKind(o[i].Val)})
			}
			return ordered{{"*", o[i].Val}}, nil
		}
	}
	return o.child("permission", path)
}

func (o *ordered) setChild(key string, c ordered) error {
	b, err := c.compact()
	if err != nil {
		return err
	}
	o.set(key, b)
	return nil
}

func (o ordered) compact() (json.RawMessage, error) {
	var buf bytes.Buffer
	buf.WriteByte('{')
	for i, f := range o {
		if i > 0 {
			buf.WriteByte(',')
		}
		k, err := marshalNoEscape(f.Key)
		if err != nil {
			return nil, err
		}
		buf.Write(k)
		buf.WriteByte(':')
		buf.Write(f.Val)
	}
	buf.WriteByte('}')
	return buf.Bytes(), nil
}

// encode 输出两个空格缩进的 JSON，末尾带换行，与 writeJSON 的格式一致。
func (o ordered) encode() ([]byte, error) {
	c, err := o.compact()
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := json.Indent(&buf, c, "", "  "); err != nil {
		return nil, err
	}
	buf.WriteByte('\n')
	return buf.Bytes(), nil
}

// marshalNoEscape 编码成紧凑 JSON，不转义 &、<、>。
func marshalNoEscape(v any) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return bytes.TrimRight(buf.Bytes(), "\n"), nil
}

// jsonKind 给报错用：JSON 值的类型名。
func jsonKind(b []byte) string {
	t := bytes.TrimSpace(b)
	if len(t) == 0 {
		return "empty"
	}
	switch t[0] {
	case '{':
		return "object"
	case '[':
		return "array"
	case '"':
		return "string"
	case 't', 'f':
		return "bool"
	case 'n':
		return "null"
	}
	return "number"
}
